def lookup_symptom(symptom: str) -> dict:
    """查询症状对应的可能疾病。

    Args:
        symptom: 症状描述

    Returns:
        {"success": bool, "data": 症状-疾病映射信息}
    """
    # 精确匹配
    if symptom in _SYMPTOM_DISEASE_MAP:
        return {"success": True, "symptom": symptom, "data": _SYMPTOM_DISEASE_MAP[symptom]}

    # 模糊匹配
    for key, value in _SYMPTOM_DISEASE_MAP.items():
        if symptom in key or key in symptom:
            return {"success": True, "symptom": key, "data": value}

    return {"success": False, "message": f"未找到「{symptom}」的相关信息。"}


def get_common_symptoms() -> list[str]:
    """返回所有已知的症状列表。"""
    return list(_SYMPTOM_DISEASE_MAP.keys())


def execute(action: str, params: dict) -> dict:
    """工具统一入口。"""
    if action == "lookup_symptom":
        return lookup_symptom(params.get("symptom", ""))
    elif action == "get_common_symptoms":
        return {"success": True, "symptoms": get_common_symptoms()}
    else:
        return {"success": False, "message": f"未知操作: {action}"}
